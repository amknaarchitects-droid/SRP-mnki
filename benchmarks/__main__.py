"""Run all SRP benchmarks and write JSON results plus a markdown summary."""

from __future__ import annotations

import argparse
import os
import time

from benchmarks import common, cow_memory, env_step_latency, network_simulation, replay_audit_overhead

SECTIONS = [
    (env_step_latency, "1. Environment step latency"),
    (network_simulation, "2. Simulated network conditions"),
    (cow_memory, "3. Copy-on-Write memory"),
    (replay_audit_overhead, "4. Replay audit overhead"),
]


def main() -> None:
    parser = argparse.ArgumentParser(description="Run all SRP benchmarks.")
    parser.add_argument("--quick", action="store_true", help="short smoke run (numbers are noisy)")
    parser.add_argument("--out", default=common.DEFAULT_OUT_DIR, help="output directory")
    args = parser.parse_args()

    env = common.environment()
    parts = [
        "# SRP benchmark results",
        "",
        "Generated by `python -m benchmarks" + (" --quick" if args.quick else "") + "`. Do not edit by hand.",
        "",
        "| | |",
        "|---|---|",
        f"| Generated (UTC) | {env['generated_utc']} |",
        f"| Library commit | `{env['commit']}` |",
        f"| Python | {env['implementation']} {env['python']} |",
        f"| OS | {env['os']} ({env['machine']}) |",
        f"| CPU | {env['cpu']}, {env['logical_cpus']} logical CPUs |",
        f"| RAM | {env['total_ram_gb']} GB |",
        f"| Mode | {'quick smoke run' if args.quick else 'full'} |",
        "",
        "All figures are wall-clock on one machine with the bundled simulated environments.",
        "They describe this reference implementation, not production RL environments.",
    ]
    for module, title in SECTIONS:
        t0 = time.perf_counter()
        print(f"[{module.NAME}] running...", flush=True)
        result = module.run(args.quick)
        result["environment"] = env
        result["duration_s"] = round(time.perf_counter() - t0, 1)
        path = common.write_json(args.out, module.NAME, result)
        table = module.render(result)
        print(table)
        print(f"[{module.NAME}] {result['duration_s']} s -> {path}\n", flush=True)
        parts += ["", f"## {title}", "", (module.__doc__ or "").strip().split("\n\n")[0], "", table,
                  "", f"Raw data: [`{module.NAME}.json`]({module.NAME}.json)"]

    summary = os.path.join(args.out, "RESULTS.md")
    with open(summary, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(parts) + "\n")
    print("wrote", summary)


if __name__ == "__main__":
    main()
